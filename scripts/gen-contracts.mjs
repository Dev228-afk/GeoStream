#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const CONTRACTS_DIR = path.join(ROOT, 'contracts');
const GO_OUT = path.join(ROOT, 'internal', 'schema', 'types_gen.go');
const TS_OUT = path.join(ROOT, 'web', 'src', 'api', 'contracts.gen.ts');

const schemas = [
  JSON.parse(fs.readFileSync(path.join(CONTRACTS_DIR, 'location-event.v1.schema.json'), 'utf8')),
  JSON.parse(fs.readFileSync(path.join(CONTRACTS_DIR, 'geofence-transition.v1.schema.json'), 'utf8')),
  JSON.parse(fs.readFileSync(path.join(CONTRACTS_DIR, 'deadletter.v1.schema.json'), 'utf8')),
];

function cap(name) {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function goType(propName, def) {
  if (def.format === 'date-time') return 'string';
  if (def.type === 'integer') {
    if (['schemaVersion', 'fenceVersion', 'partition'].includes(propName)) return 'int';
    return 'int64';
  }
  if (def.type === 'number') return 'float64';
  if (def.type === 'string') return 'string';
  throw new Error(`Unsupported schema property type for Go: ${propName}`);
}

function tsType(def) {
  if (Array.isArray(def.enum)) return def.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (def.const !== undefined) return JSON.stringify(def.const);
  if (def.type === 'integer' || def.type === 'number') return 'number';
  if (def.type === 'string') return 'string';
  throw new Error(`Unsupported schema property type for TS: ${JSON.stringify(def)}`);
}

function renderGo() {
  const lines = [
    '// Code generated by scripts/gen-contracts.mjs; DO NOT EDIT.',
    'package schema',
    '',
  ];
  for (const s of schemas) {
    lines.push(`type ${s.title} struct {`);
    for (const [k, def] of Object.entries(s.properties)) {
      lines.push(`\t${cap(k)} ${goType(k, def)} \`json:"${k}"\``);
    }
    lines.push('}', '');
  }
  return lines.join('\n');
}

function renderTs() {
  const lines = [
    '// Code generated by scripts/gen-contracts.mjs; DO NOT EDIT.',
    '',
  ];
  for (const s of schemas) {
    lines.push(`export interface ${s.title} {`);
    const req = new Set(s.required ?? []);
    for (const [k, def] of Object.entries(s.properties)) {
      const opt = req.has(k) ? '' : '?';
      lines.push(`  ${k}${opt}: ${tsType(def)};`);
    }
    lines.push('}', '');
  }
  return lines.join('\n');
}

const checkOnly = process.argv.includes('--check');
const goContent = renderGo();
const tsContent = renderTs();

if (checkOnly) {
  const existingGo = fs.existsSync(GO_OUT) ? fs.readFileSync(GO_OUT, 'utf8') : '';
  const existingTs = fs.existsSync(TS_OUT) ? fs.readFileSync(TS_OUT, 'utf8') : '';
  if (existingGo !== goContent || existingTs !== tsContent) {
    console.error('Generated contracts out of date! Run node scripts/gen-contracts.mjs');
    process.exit(1);
  }
  console.log('Contracts check passed: Go and TS generated types match JSON schemas.');
} else {
  fs.mkdirSync(path.dirname(GO_OUT), { recursive: true });
  fs.mkdirSync(path.dirname(TS_OUT), { recursive: true });
  fs.writeFileSync(GO_OUT, goContent, 'utf8');
  fs.writeFileSync(TS_OUT, tsContent, 'utf8');
  console.log(`Generated:\n- ${path.relative(ROOT, GO_OUT)}\n- ${path.relative(ROOT, TS_OUT)}`);
}

